"""
Generates realistic Indian Smartphone & Consumer Electronics Retail/Distribution data
for the 'Zenith Mobile' showcase inside Retail AI Suite.

Grounded in real Indian handset distribution economics:
- MRP / MOP (Market Operating Price) / Net Landing Cost (NLC) / Shopkeeper Margin (INR)
- Monthly Slab Credit Notes (QPS / Activation-linked payouts)
- Distributor Secondary Billing vs Verified SIM/IMEI Activations
- NBFC Zero-Down-Payment EMI Counter Coverage (Bajaj Finance / TVS Credit / IDFC)
- In-Shop Promoter (ISD) counts, Rival Brand Dealer Schemes, Variant Stockouts
- Weekly De-Censored Demand & Probabilistic Forecasts (compatible with ForecastCanvas)
- Doorstep Service-at-Home WhatsApp Triage & Factory SMT Batch Defect Traceability
"""

import json
import math
import random
from pathlib import Path

random.seed(108)


def build_weekly_sku_series(
    sku_id: str,
    name: str,
    subcategory: str,
    archetype: str,
    routed_model: str,
    mop_inr: int,
    shop_landing_inr: int,
    unit_cogs_inr: int,
    current_inventory: int,
    on_order_units: int,
    lead_time_weeks: int,
    target_quantile: int,
    base_weekly_demand: float,
    seasonality_amp: float,
    phase_shift: float,
    promo_weeks_hist: list[int],
    promo_weeks_future: list[int],
    censored_weeks_hist: list[int],
    trend_slope: float,
    llm_adjustment_pct: float,
    llm_confidence: float,
    llm_trigger_event: str,
    llm_rationale: str,
    action_type: str,
    action_title: str,
    action_summary: str,
    recommended_units_delta: int,
    transfer_route: str,
    legacy_wape: float,
    statsforecast_wape: float,
    chronos2_wape: float,
    addl_wape: float,
    availability_before: float,
    availability_after: float,
    excess_weeks_before: float,
    excess_weeks_after: float,
    financial_impact_inr: int,
    color_hex: str,
    swatch_name: str,
    store_cluster: str,
):
    history = []
    for w in range(1, 25):
        t = w - 25
        seasonal = 1.0 + seasonality_amp * math.sin(2 * math.pi * (w + phase_shift) / 26.0)
        trend = 1.0 + trend_slope * (w / 24.0)
        is_promo = w in promo_weeks_hist
        promo_mult = 1.55 if is_promo else 1.0
        noise = random.uniform(0.92, 1.08)

        true_demand = max(40, round(base_weekly_demand * seasonal * trend * promo_mult * noise))
        is_censored = w in censored_weeks_hist
        if is_censored:
            observed_sales = round(true_demand * random.uniform(0.56, 0.66))
            ending_inventory = 0
        else:
            observed_sales = true_demand
            ending_inventory = max(120, round(current_inventory * random.uniform(0.72, 1.28)))

        erp_hist_forecast = round(observed_sales * random.uniform(0.83, 1.14))

        history.append({
            "weekIndex": t,
            "weekLabel": f"W{t}",
            "dateLabel": f"Wk {w}",
            "observedSales": observed_sales,
            "trueLatentDemand": true_demand,
            "censoredUnits": max(0, true_demand - observed_sales),
            "isStockoutCensored": is_censored,
            "isPromo": is_promo,
            "endingInventory": ending_inventory,
            "erpHistoricalForecast": erp_hist_forecast,
        })

    forecast = []
    inv_status_quo = current_inventory
    inv_approved = current_inventory

    for fw in range(1, 13):
        w_abs = 24 + fw
        seasonal = 1.0 + seasonality_amp * math.sin(2 * math.pi * (w_abs + phase_shift) / 26.0)
        trend = 1.0 + trend_slope * (w_abs / 24.0)
        is_promo = fw in promo_weeks_future
        promo_mult = 1.65 if is_promo else 1.0

        chronos_p50 = max(50, round(base_weekly_demand * seasonal * trend * promo_mult))
        spread = 0.13 + 0.011 * fw + (0.07 if is_promo else 0.0)
        chronos_p10 = max(20, round(chronos_p50 * (1.0 - spread)))
        chronos_p90 = round(chronos_p50 * (1.0 + spread * 1.15))

        classical_p50 = round(chronos_p50 * (0.78 if is_promo else 0.93))
        legacy_erp = round(chronos_p50 * (0.68 if is_promo else 0.87))

        ctx_weight = 1.0 if fw <= 6 else 0.55
        adj_mult = 1.0 + (llm_adjustment_pct / 100.0) * ctx_weight
        addl_p50 = max(25, round(chronos_p50 * adj_mult))
        addl_p10 = max(15, round(chronos_p10 * adj_mult))
        addl_p90 = round(chronos_p90 * adj_mult)

        safety_floor = round(addl_p50 * 0.65)
        if fw == lead_time_weeks:
            inv_status_quo += on_order_units
            inv_approved += on_order_units + max(0, recommended_units_delta)

        inv_status_quo = max(0, inv_status_quo - addl_p50)
        inv_approved = max(safety_floor, inv_approved - addl_p50)

        forecast.append({
            "weekIndex": fw,
            "weekLabel": f"W+{fw}",
            "isPromo": is_promo,
            "legacyErpForecast": legacy_erp,
            "classicalForecast": classical_p50,
            "chronosP10": chronos_p10,
            "chronosP50": chronos_p50,
            "chronosP90": chronos_p90,
            "addlP10": addl_p10,
            "addlP50": addl_p50,
            "addlP90": addl_p90,
            "projectedInventoryStatusQuo": inv_status_quo,
            "projectedInventoryApproved": inv_approved,
            "safetyStockFloor": safety_floor,
        })

    gross_margin_pct = round(((shop_landing_inr - unit_cogs_inr) / shop_landing_inr) * 100, 1)

    return {
        "skuId": sku_id,
        "name": name,
        "category": "Smartphones",
        "subcategory": subcategory,
        "archetype": archetype,
        "routedModel": routed_model,
        "retailPrice": mop_inr,
        "unitCost": unit_cogs_inr,
        "shopLandingPrice": shop_landing_inr,
        "grossMarginPct": gross_margin_pct,
        "currentInventory": current_inventory,
        "onOrderUnits": on_order_units,
        "leadTimeWeeks": lead_time_weeks,
        "remainingSellingWeeks": 18,
        "targetQuantile": target_quantile,
        "llmAdjustmentPct": llm_adjustment_pct,
        "llmGuardrailStatus": "APPROVED_BY_GUARDRAIL",
        "llmConfidence": llm_confidence,
        "llmTriggerEvent": llm_trigger_event,
        "llmRationale": llm_rationale,
        "actionType": action_type,
        "actionTitle": action_title,
        "actionSummary": action_summary,
        "recommendedUnitsDelta": recommended_units_delta,
        "recommendedMarkdownPct": 0,
        "transferRoute": transfer_route,
        "metrics": {
            "legacyWape": legacy_wape,
            "statsForecastWape": statsforecast_wape,
            "chronos2Wape": chronos2_wape,
            "addlWape": addl_wape,
            "excessWeeksBefore": excess_weeks_before,
            "excessWeeksAfter": excess_weeks_after,
            "availabilityBefore": availability_before,
            "availabilityAfter": availability_after,
            "financialImpactUsd": round(financial_impact_inr / 84),
            "financialImpactInr": financial_impact_inr,
            "workingCapitalDeltaUsd": round((financial_impact_inr * 0.4) / 84),
            "markdownSavedUsd": round((financial_impact_inr * 0.2) / 84),
            "lostSalesPreventedUsd": round((financial_impact_inr * 0.4) / 84),
        },
        "priorityScore": 96,
        "colorHex": color_hex,
        "swatchName": swatch_name,
        "silhouetteType": "smartphone",
        "storeCluster": store_cluster,
        "history": history,
        "forecast": forecast,
    }


